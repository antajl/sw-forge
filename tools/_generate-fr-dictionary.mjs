import fs from 'fs';
import vm from 'vm';

function loadEn() {
  const src = fs.readFileSync('js/core/translations-en.js', 'utf8');
  const sandbox = {};
  vm.runInNewContext(`${src}\nsandbox.out = TRANSLATIONS_EN;`, { sandbox });
  return sandbox.out;
}

function escapeJs(s) {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r\n/g, '\n')
    .replace(/\r/g, '\n');
}

function formatEntry(key, value) {
  const s = String(value);
  if (s.includes('\n')) {
    const lines = s.split('\n');
    return `  ${key}:\n    '${escapeJs(lines[0])}' +\n    '${escapeJs(lines.slice(1).join('\n'))}',`;
  }
  return `  ${key}: '${escapeJs(s)}',`;
}

